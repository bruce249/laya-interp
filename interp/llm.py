"""OpenAI-compatible client with an on-Volume response cache, plus the generation tasks that need it.

Model ids are resolved at runtime from the key's model list (env LLM_BULK / LLM_CAREFUL override).
"""

from __future__ import annotations

import concurrent.futures as cf
import hashlib
import json
import os
import pathlib
import random

CACHE = pathlib.Path("/store/llm_cache")


def client():
    from openai import OpenAI

    base = os.environ.get("LLM_BASE_URL")
    return OpenAI(base_url=base) if base else OpenAI()


def pick_models() -> dict:
    """Bulk and careful model ids. Preference order is only a default; env vars win."""
    names = sorted(m.id for m in client().models.list().data)
    chat = [n for n in names if n.startswith("gpt-") and not any(x in n for x in
                                                                 ("audio", "realtime", "image", "tts", "transcribe",
                                                                  "search", "embedding"))]
    mini = [n for n in chat if "mini" in n or "nano" in n or "luna" in n.lower()]
    big = [n for n in chat if n not in mini]
    return {"bulk": os.environ.get("LLM_BULK") or (mini[-1] if mini else chat[-1]),
            "careful": os.environ.get("LLM_CAREFUL") or (big[-1] if big else chat[-1]),
            "available": chat}


def ask(model: str, system: str, user: str, json_mode: bool = True) -> str:
    key = hashlib.sha256(json.dumps([model, system, user, json_mode]).encode()).hexdigest()
    path = CACHE / f"{key}.json"
    if path.exists():
        return json.loads(path.read_text())["text"]
    kw = {"response_format": {"type": "json_object"}} if json_mode else {}
    resp = client().chat.completions.create(model=model, messages=[{"role": "system", "content": system},
                                                                   {"role": "user", "content": user}], **kw)
    text = resp.choices[0].message.content or ""
    CACHE.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"model": model, "text": text,
                                "usage": resp.usage.model_dump() if resp.usage else None}))
    return text


def ask_many(model, system, users, workers: int = 16) -> list[str | None]:
    def one(u):
        try:
            return ask(model, system, u)
        except Exception as exc:  # recorded as a miss, not fatal
            return json.dumps({"error": f"{type(exc).__name__}: {str(exc)[:200]}"})
    with cf.ThreadPoolExecutor(workers) as ex:
        return list(ex.map(one, users))


def usage_total() -> dict:
    tot = {"prompt_tokens": 0, "completion_tokens": 0, "calls": 0}
    for p in CACHE.glob("*.json"):
        u = json.loads(p.read_text()).get("usage") or {}
        tot["prompt_tokens"] += u.get("prompt_tokens", 0)
        tot["completion_tokens"] += u.get("completion_tokens", 0)
        tot["calls"] += 1
    return tot


# ----- natural counterfactuals for real jailbreaks (C4) -----

CF_SYSTEM = (
    "You edit text for a research dataset on prompt-safety classifiers. Given a prompt that tries to make an AI "
    "assistant ignore its rules, return the smallest edit that removes only the rule-evasion attempt (role-play "
    "override, 'ignore instructions', developer-mode framing, etc.) while keeping every other word, the topic and "
    "the length as close as possible. Do not add any harmful content and do not answer the prompt. "
    'Reply as JSON: {"edited": "...", "removed": "short description of what was removed"}')


def counterfactuals(texts: list[str], model: str) -> list[dict]:
    outs = ask_many(model, CF_SYSTEM, [f"Prompt:\n{t}" for t in texts])
    rows = []
    for t, o in zip(texts, outs):
        try:
            js = json.loads(o)
            if "edited" in js and js["edited"].strip() and js["edited"].strip() != t.strip():
                rows.append({"original": t, "edited": js["edited"], "removed": js.get("removed", "")})
        except Exception:
            pass
    return rows


# ----- C3 items generated by an LLM, then verified by a second pass -----

C3_SYSTEM = (
    "You write items for a reading-comprehension dataset. Each item is a short factual-sounding passage (3-5 "
    "sentences, fictional entities are fine) and a yes/no question whose answer is fully determined by the passage. "
    'Reply as JSON: {"items": [{"state": "...", "question": "...?", "answer": true|false, '
    '"evidence": "explicit"|"implied"}]}')
C3_VERIFY = (
    "Read the passage and answer the question using only the passage. "
    'Reply as JSON: {"answer": true|false|null} (null if the passage does not determine it).')
TOPICS = ["a small bakery", "a train timetable change", "a software release", "a museum exhibit", "a school trip",
          "a city council vote", "a hiking trail", "a lab experiment", "a shipping delay", "a sports match",
          "a library policy", "a weather warning", "a product recall", "a job posting", "a concert",
          "a hospital visit rule", "a bank holiday", "a recipe", "a bike rental", "a festival"]


def c3_items(n: int, bulk: str, careful: str, seed: int = 0) -> list[dict]:
    rng = random.Random(seed)
    prompts = []
    per = 10
    for i in range(n // per + 2):
        want_true = per // 2
        prompts.append(f"Write {per} items about {rng.choice(TOPICS)}. Exactly {want_true} answers must be true "
                       f"and {per - want_true} false. Half the items should need an inference (evidence: implied). "
                       f"Vary the wording; avoid the words 'true', 'false', 'yes', 'no' in passages. Batch id {i}.")
    raw = []
    for o in ask_many(bulk, C3_SYSTEM, prompts):
        try:
            raw += json.loads(o).get("items", [])
        except Exception:
            pass
    raw = [r for r in raw if isinstance(r, dict) and r.get("state") and r.get("question")
           and isinstance(r.get("answer"), bool)]
    checks = ask_many(careful, C3_VERIFY, [f"Passage: {r['state']}\nQuestion: {r['question']}" for r in raw])
    kept = []
    for r, c in zip(raw, checks):
        try:
            if json.loads(c).get("answer") is r["answer"]:
                kept.append(r)
        except Exception:
            pass
    rng.shuffle(kept)
    out = []
    for j, r in enumerate(kept[:n]):
        q = r["question"].strip()
        out.append({"id": f"llmc3_{j}", "state": r["state"], "question": q if q.endswith("?") else q + "?",
                    "gold": int(r["answer"]), "evidence": r.get("evidence", ""),
                    "split": "heldout" if j % 10 < 3 else "main"})
    return out
